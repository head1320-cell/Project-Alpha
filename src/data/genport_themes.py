def get_theme_tree(member_count_fn=None) -> dict:
    """17그룹 → 88세부 구조 + (선택) 세부별 멤버 수.

    member_count_fn(subsector)->int 가 주어지면 실데이터 기준 카운트, 없으면 시드 수."""
    groups = []
    total_sub = 0
    for grp, subs in THEME_TREE.items():
        items = []
        for sub in subs:
            n = (member_count_fn(sub) if member_count_fn
                 else len(THEME_SEED.get(sub, [])))
            items.append({"id": f"theme:{sub}", "label": sub, "size": int(n)})
            total_sub += 1
        groups.append({"id": f"themegroup:{grp}", "label": grp, "subsectors": items})
    return {"groups": groups, "group_count": len(THEME_TREE), "subsector_count": total_sub}


def theme_members(subsector: str) -> list[str]:
    """세부업종 → 시드 종목코드 (확신 대표주). 미시드면 빈 리스트."""
    return list(THEME_SEED.get((subsector or "").strip(), []))


def group_members(group: str) -> list[str]:
    """그룹 → 하위 세부업종 시드 종목 합집합."""
    out: list[str] = []
    for sub in THEME_TREE.get((group or "").strip(), []):
        out.extend(THEME_SEED.get(sub, []))
    return sorted(set(out))


# 큐레이션 업종명(stock_master.STOCK_SECTOR) → 젠포트 그룹
