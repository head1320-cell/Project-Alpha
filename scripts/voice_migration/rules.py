def _fail(verb, noun):
    return [(_OBJ + verb + r" 못했어요" + _END, r"\1 " + noun), (_HEAD + verb + r" 못했어요" + _END, noun)]
def _ing(verb, noun):
    return [(_OBJ + verb + r" 중이에요" + _END, r"\1 " + noun + " 중"), (_HEAD + verb + r" 중이에요" + _END, noun + " 중")]

