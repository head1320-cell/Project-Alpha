#: 한글로 끝나지 않는 이름의 끝소리 받침(읽는 소리 기준) — 에스·에이·씨·에프는 받침 없음 · 엠(VaR→바) …
_LATIN_FINAL = {"VaR": True, "ES": False, "CVA": False, "IRC": False, "DCF": False}


def _has_final(name: str) -> tuple[bool, bool]:
    """(받침 있음, 그 받침이 ㄹ) — 괄호 풀이는 그 앞 한글로 본다."""
    core = re.sub(r"\([^)]*\)$", "", name).strip()
    last = core[-1]
    if "가" <= last <= "힣":
        jong = (ord(last) - 0xAC00) % 28
        return jong != 0, jong == 8
    for k, v in _LATIN_FINAL.items():
        if core.endswith(k): return v, k == "VaR"
    return False, False


_PART = {("을", "를"): 0, ("이", "가"): 0, ("은", "는"): 0, ("과", "와"): 0}


def _particle(new: str, p: str) -> str:
    fin, rieul = _has_final(new)
    for (a, b) in _PART:
        if p in (a, b): return a if fin else b
    if p in ("으로", "로"): return "으로" if fin and not rieul else "로"
    return p


def _rep(new):
    def f(m):
        return new + m.group(1) + (_particle(new, m.group(2)) if m.group(2) else "")
    return f


